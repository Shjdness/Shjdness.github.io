import type {D1Database,D1PreparedStatement,D1Result} from '@cloudflare/workers-types';
import {isD1QuotaError} from './write-budget';

export type PostCreateOperation={ownerId:number;clientKey:string;requestHash:string};
export class PostCreateConflictError extends Error {}
const receiptKey=(operation:PostCreateOperation)=>`post-create:v1:${operation.ownerId}:${operation.clientKey}`;

export async function postRequestHash(value:Record<string,unknown>) {
  const digest=await crypto.subtle.digest('SHA-256',new TextEncoder().encode(JSON.stringify(value)));
  return Array.from(new Uint8Array(digest),byte=>byte.toString(16).padStart(2,'0')).join('');
}

/** Receipts are private and account-scoped. Replays never recreate deleted posts. */
export async function findPostCreate(db:D1Database,operation:PostCreateOperation) {
  const row=await db.prepare('SELECT value FROM info WHERE key=?').bind(receiptKey(operation)).first<{value:string}>();
  if(!row)return;
  const receipt=JSON.parse(row.value) as {requestHash?:string;insertedId?:number;deleted?:boolean};
  if(!Number.isSafeInteger(receipt.insertedId)||Number(receipt.insertedId)<=0)throw Error('Invalid post creation receipt');
  if(receipt.deleted)throw new PostCreateConflictError('此创建操作对应的记录已删除；请保留本地草稿并使用新的创建操作');
  if(typeof receipt.requestHash!=='string')throw Error('Invalid post creation receipt');
  if(receipt.requestHash!==operation.requestHash)throw new PostCreateConflictError('此创建操作已有不同内容；请保留本地草稿并核对云端记录');
  const post=await db.prepare('SELECT id FROM feeds WHERE id=? AND uid=?').bind(receipt.insertedId,operation.ownerId).first<{id:number}>();
  if(!post)throw new PostCreateConflictError('此创建操作对应的记录已不存在；请保留本地草稿并使用新的创建操作');
  return {insertedId:post.id};
}

/** Keep a tombstone so a reused SQLite rowid cannot turn an old retry into an
 * acknowledgement of an unrelated new record. Called only after route auth. */
export async function deletePostWithReceipts(db:D1Database,ownerId:number,id:number) {
  const prefix=`post-create:v1:${ownerId}:`;
  await db.batch([
    db.prepare("UPDATE info SET value=json_remove(json_set(value,'$.deleted',json('true')),'$.requestHash') WHERE key>=? AND key<? AND json_extract(value,'$.insertedId')=?").bind(prefix,prefix+'\uffff',id),
    db.prepare('DELETE FROM feeds WHERE id=? AND uid=?').bind(id,ownerId),
  ]);
}

// Capture the immediately preceding post INSERT's rowid once. Materialization
// prevents relation INSERTs from changing the ID used for subsequent tag rows.
export const NEW_POST_TAGS_SQL=`WITH new_feed AS MATERIALIZED (SELECT last_insert_rowid() AS id)
  INSERT INTO feed_hashtags(feed_id,hashtag_id)
  SELECT new_feed.id,CAST(tags.value AS INTEGER) FROM new_feed CROSS JOIN json_each(?) AS tags`;

/** The insert is generated by Drizzle. A receipt UPDATE doesn't change rowid;
 * no other INSERT or vocabulary write may intervene before binding the tags. */
export async function createPostWithTags(db:D1Database,insert:{sql:string;params:unknown[]},tagIds:number[],operation?:PostCreateOperation) {
  const statements:D1PreparedStatement[]=[];
  if(operation)statements.push(db.prepare('INSERT INTO info(key,value) VALUES(?,?)').bind(receiptKey(operation),JSON.stringify({requestHash:operation.requestHash})));
  statements.push(db.prepare(insert.sql).bind(...insert.params));
  if(operation)statements.push(db.prepare("UPDATE info SET value=json_object('requestHash',?,'insertedId',last_insert_rowid()) WHERE key=?").bind(operation.requestHash,receiptKey(operation)));
  if(tagIds.length)statements.push(db.prepare(NEW_POST_TAGS_SQL).bind(JSON.stringify(tagIds)));
  let results:D1Result<{id:number}>[];
  try{results=await db.batch<{id:number}>(statements);}
  catch(error) {
    // A competing same-key batch can commit after the route's initial read.
    // Preserve quota errors and do not mask the original failure if lookup fails.
    if(operation&&!isD1QuotaError(error)) {
      try{const saved=await findPostCreate(db,operation);if(saved)return saved;}
      catch(lookupError){if(lookupError instanceof PostCreateConflictError)throw lookupError;}
    }
    throw error;
  }
  const result=results[operation?1:0];
  const id=result.results?.[0]?.id;
  if(!Number.isSafeInteger(id)||id<=0)throw Error('Post creation was not acknowledged');
  return {insertedId:id};
}
